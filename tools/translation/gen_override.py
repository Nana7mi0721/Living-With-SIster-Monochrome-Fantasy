#!/usr/bin/env python3
r"""Build the runtime text-overlay table for the Rust engine.

Reads the per-line A/B sheet (work/translation/final/wolf_text_AB.jsonl) and writes
work/translation/final/wolf_override.tsv: event<TAB>pc<TAB>text, consumed by
wolf_game::translation::TextOverlay (env WOLF_TEXT_OVERLAY).

Only rows where the fan translation (bimeng) won AND its body is pure literal text
(no WOLF escape codes, after dropping MV speaker tags \N<...> / \N[...]) are
written.  A row that carries a variable/colour code keeps the shipped official
string, because remapping MV escape syntax onto WOLF's is not safe to guess.  The
official string's outline prefix (\E) is prepended so the translated line keeps the
same weight as the original.
"""
import json, os

BS = chr(92)
SRC = "work/translation/final/wolf_text_AB.jsonl"
OUT = "work/translation/final/wolf_override.tsv"


def strip_names(s):
    out = []
    i = 0
    n = len(s)
    while i < n:
        if s[i] == BS and i + 1 < n and s[i + 1] == "N":
            nxt = s[i + 2] if i + 2 < n else ""
            if nxt == "<":
                j = s.find(">", i + 3)
                i = j + 1 if j != -1 else n
                continue
            if nxt == "[":
                j = s.find("]", i + 3)
                i = j + 1 if j != -1 else n
                continue
        out.append(s[i])
        i += 1
    return "".join(out)


def prefix_of(official):
    return BS + "E" if official.startswith(BS + "E") else (BS + "e" if official.startswith(BS + "e") else "")


def esc(text):
    return text.replace(BS, BS + BS).replace(chr(10), BS + "n").replace(chr(9), BS + "t").replace(chr(13), "")


def main():
    rows = [json.loads(l) for l in open(SRC, encoding="utf-8")]
    records = []
    skipped = {"not_bimeng": 0, "no_text": 0, "has_escape": 0, "empty": 0}
    for r in rows:
        if r.get("source") != "bimeng":
            skipped["not_bimeng"] += 1
            continue
        body = strip_names(r.get("final_zh") or "")
        if not body:
            skipped["no_text"] += 1
            continue
        if BS in body:
            skipped["has_escape"] += 1
            continue
        text = prefix_of(r.get("official_zh") or "") + body
        if not text.strip():
            skipped["empty"] += 1
            continue
        records.append((r.get("event"), r.get("index"), text))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline=chr(10)) as f:
        f.write("# event\tpc\ttext  -- generated by gen_override.py; do not edit by hand" + chr(10))
        for event, index, text in records:
            f.write("%s\t%s\t%s%s" % (event, index, esc(text), chr(10)))

    events = len({e for e, _, _ in records})
    total_msgs = len(rows)
    print("wrote", OUT)
    print("records:", len(records), "events:", events, "of", total_msgs, "text rows")
    print("skipped:", skipped)
    for event, index, text in records[:5]:
        print("  sample %s/%s %r" % (event, index, text))


if __name__ == "__main__":
    main()
